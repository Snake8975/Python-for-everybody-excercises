width = 17
height = 12.0

# Printing the parameters with their respective values
print("The value of width is:", width)  
print("The value of height is:", height)  

# Calculating and printing the arithmetic operations and their types
print(width//2)
print(type(width//2))

print(width/2.0)
print(type(width/2.0))

print(height/3)
type(height/3)
print(type(height/3))

print(1 + 2 * 5)
type(1 + 2 * 5)
print(type(1 + 2 * 5))

# Calculating and printing the area of a rectangle
print(width * height)
